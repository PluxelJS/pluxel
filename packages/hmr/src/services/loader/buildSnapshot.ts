import type { Context, PluginConstructor } from '@pluxel/core'
import { genObjectFromRawEntries, genObjectFromValues } from 'knitwork'
import type { PluginRegistry } from './PluginRegistry'

interface SnapshotDeps {
	ctx: Context
	registry: PluginRegistry
	isRunning(target: PluginConstructor | string): boolean
}

type Row = {
	name: string
	moduleId: string
	exportKey: string
	alias: string
}

export function buildSnapshot({ ctx, registry, isRunning }: SnapshotDeps): string {
	const rows: Row[] = []
	for (const [name, ctor] of registry.names) {
		if (!isRunning(ctor)) continue
		const moduleId = registry.name2PathMap.get(name)
		const exportKey = registry.getExportKeyByName(name)
		if (!moduleId || !exportKey) continue
		rows.push({ name, moduleId, exportKey, alias: aliasFor(name) })
	}

	rows.sort((a, b) =>
		a.name === b.name ? a.moduleId.localeCompare(b.moduleId) : a.name.localeCompare(b.name),
	)

	const used = new Set<string>()
	for (const r of rows) {
		const alias = r.alias
		if (!used.has(alias)) {
			used.add(alias)
			r.alias = alias
			continue
		}

		const withFile = `${alias}__${basenameFor(r.moduleId)}`
		if (!used.has(withFile)) {
			used.add(withFile)
			r.alias = withFile
			continue
		}

		const keySuffix = r.exportKey === 'default' ? 'default' : safeIdent(r.exportKey)
		const withKey = `${withFile}__${keySuffix}`
		if (!used.has(withKey)) {
			used.add(withKey)
			r.alias = withKey
			continue
		}

		let i = 2
		while (used.has(`${withKey}__${i}`)) i++
		const finalAlias = `${withKey}__${i}`
		used.add(finalAlias)
		r.alias = finalAlias
	}

	const header =
		'// @generated by LoaderService.buildSnapshot\n' +
		`// ${new Date().toISOString()}\n` +
		'/* eslint-disable */\n'

	const grouped = new Map<string, Row[]>()
	for (const r of rows) {
		const list = grouped.get(r.moduleId) ?? []
		list.push(r)
		grouped.set(r.moduleId, list)
	}

	const importLines: string[] = []
	const exportAliases = new Set<string>()
	for (const [moduleId, list] of grouped) {
		const defaultItem = list.find((e) => e.exportKey === 'default')
		const namedItems = list.filter((e) => e.exportKey !== 'default')
		if (defaultItem && namedItems.length > 0) {
			const namedPart = namedItems.map((e) => `${e.exportKey} as ${e.alias}`).join(', ')
			importLines.push(
				`import ${defaultItem.alias}, { ${namedPart} } from ${JSON.stringify(moduleId)};`,
			)
		} else if (defaultItem) {
			importLines.push(`import ${defaultItem.alias} from ${JSON.stringify(moduleId)};`)
		} else if (namedItems.length > 0) {
			const namedPart = namedItems.map((e) => `${e.exportKey} as ${e.alias}`).join(', ')
			importLines.push(`import { ${namedPart} } from ${JSON.stringify(moduleId)};`)
		}

		for (const e of list) exportAliases.add(e.alias)
	}

	const entries: [string, string][] = rows.map((r) => {
		const { configRecord } = ctx.configService.getConfig(r.name)
		const cfg = genObjectFromValues(stripUndef(configRecord))
		const valCode = `{ ctor: ${r.alias}, config: ${cfg} }`
		return [r.name, valCode]
	})
	const registryCode = genObjectFromRawEntries(entries)

	const exportLine = `export { ${[...exportAliases].join(', ')} };`
	const body = `export const registry = ${registryCode} as const;\n \n    export type PluginName = keyof typeof registry;\n`
	return [header, ...importLines, '', exportLine, '', body].join('\n')
}

function aliasFor(name: string): string {
	let id = 'P_' + name.replace(/[^A-Za-z0-9_$]/g, '_')
	if (/^[0-9]/.test(id)) id = '_' + id
	return id
}

function basenameFor(path: string): string {
	const normalized = path.replace(/\\/g, '/')
	const last = normalized.split('/').pop() || ''
	const stem = last.replace(/\.[A-Za-z0-9]+$/, '')
	return safeIdent(stem)
}

function safeIdent(s: string): string {
	let id = s.replace(/[^A-Za-z0-9_$]/g, '_')
	if (/^[0-9]/.test(id)) id = '_' + id
	return id
}

function stripUndef<T>(obj: T): T {
	if (obj == null || typeof obj !== 'object') return obj
	if (Array.isArray(obj)) return obj.map(stripUndef) as unknown as T
	const out: Record<string, unknown> = {}
	for (const [k, v] of Object.entries(obj as any)) {
		if (v === undefined) continue
		out[k] = stripUndef(v as any)
	}
	return out as T
}
