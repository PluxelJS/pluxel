import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { compile, optimize } from '@tailwindcss/node'

const directory = new URL('../src/showcase/', import.meta.url)
const [source, template] = await Promise.all([
	readFile(new URL('report-card.css', directory), 'utf8'),
	readFile(new URL('report-card.tsx', directory), 'utf8'),
])
const compiler = await compile(source, {
	base: fileURLToPath(directory),
	onDependency() {},
})
const candidates = [...template.matchAll(/className="([^"]+)"/g)].flatMap((match) =>
	match[1].split(/\s+/),
)
const css = optimize(compiler.build(candidates), { minify: true }).code
await writeFile(
	new URL('report-card-css.ts', directory),
	`// Generated by scripts/compile-report-card-css.mjs.\nexport const REPORT_CARD_CSS =\n\t'${css.replaceAll('\\', '\\\\').replaceAll("'", "\\'").replaceAll('\n', '\\n')}'\n`,
)
